// Generates public/.htaccess (HTTPS, caching, compression, 404, and 301 redirects).
import { readFileSync, writeFileSync } from 'node:fs';

const { exact, patterns } = JSON.parse(readFileSync('redirects/redirects.json', 'utf8'));
const origin = 'https://keithgoode.com';

const lines = [];
lines.push('# GENERATED by scripts/build-htaccess.mjs. Edit redirects/redirects.json instead.', '');
lines.push(
  'RewriteEngine On',
  '# Force HTTPS',
  'RewriteCond %{HTTPS} !=on',
  'RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]',
  '',
  'ErrorDocument 404 /404.html',
  'Options -Indexes',
  'DirectoryIndex index.html',
  ''
);
lines.push('# Old WordPress URLs');
const esc = (str) => str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
for (const r of exact) {
  const path = r.from.replace(/^\//, '').replace(/\/$/, '');
  lines.push(`RewriteRule ^${esc(path)}/?$ ${origin}${r.to} [R=301,L]`);
}
lines.push('');
for (const r of patterns) {
  lines.push(`RewriteRule ${r.from.replace(/^\^\//, '^')} ${origin}${r.to} [R=301,L]`);
}
lines.push(
  '',
  '<IfModule mod_deflate.c>',
  '  AddOutputFilterByType DEFLATE text/html text/css application/javascript application/json image/svg+xml',
  '</IfModule>',
  '',
  '<IfModule mod_expires.c>',
  '  ExpiresActive On',
  '  ExpiresByType text/html "access plus 0 seconds"',
  '  ExpiresByType text/css "access plus 1 year"',
  '  ExpiresByType application/javascript "access plus 1 year"',
  '  ExpiresByType image/webp "access plus 1 year"',
  '  ExpiresByType image/png "access plus 1 year"',
  '  ExpiresByType image/jpeg "access plus 1 year"',
  '  ExpiresByType image/svg+xml "access plus 1 year"',
  '  ExpiresByType font/woff2 "access plus 1 year"',
  '</IfModule>',
  ''
);
writeFileSync('public/.htaccess', lines.join('\n'));
console.log(`.htaccess written: ${exact.length} exact + ${patterns.length} pattern redirects`);
